"""Generate the original ZYG tight output decimator (Python stdlib only).

131 taps, Kaiser beta 10, cutoff .45 of the input Nyquist. The odd centre
index 65 gives integer base-rate delays for both 2x and cascaded 4x paths.
"""
import math
from pathlib import Path


def i0(x):
    term = result = 1.0
    for n in range(1, 80):
        term *= (x / (2 * n)) ** 2
        result += term
    return result


def coefficients():
    values = []
    for index in range(131):
        t = index - 65
        sinc = .45 if t == 0 else math.sin(math.pi * .45 * t) / (math.pi * t)
        values.append(sinc * i0(10 * math.sqrt(max(0, 1 - (t / 65) ** 2))) / i0(10))
    total = sum(values)
    return [v / total for v in values]


if __name__ == '__main__':
    values = coefficients()
    text = '#pragma once\n// Generated by tools/generate_output_fir.py; original ZYG Kaiser/sinc design.\n#include <array>\n\nnamespace zyg {\ninline constexpr std::array<double, 131> tightOversamplingFir {\n'
    text += ''.join('    ' + ', '.join(format(v, '.17g') for v in values[i:i+4]) + ',\n' for i in range(0, len(values), 4))
    text += '};\n}\n'
    path = Path(__file__).resolve().parent.parent / 'src/OutputFir.h'
    path.write_text(text, encoding='utf-8', newline='\n')
    print(path)
