"""Generate ZYG's original four-phase causal modulation reconstruction FIR.

Windowed sinc, cutoff .5 cycles/input sample, Kaiser beta 8, radius 24
input samples. Each phase has unity DC gain. No third-party coefficient table.
Run from any directory; output is deterministic and needs only Python stdlib.
"""
import math
from pathlib import Path


def i0(x):
    term = result = 1.0
    for n in range(1, 60):
        term *= (x / (2 * n)) ** 2
        result += term
    return result


def coefficients():
    phases = []
    for phase in range(4):
        row = []
        # History is contiguous, oldest to newest; k=0 in convolution is newest.
        for oldest in range(48):
            t = 47 - oldest + phase / 4 - 24
            sinc = 1.0 if abs(t) < 1e-12 else 0.0 if abs(t - round(t)) < 1e-12 else math.sin(math.pi * t) / (math.pi * t)
            row.append(sinc * i0(8 * math.sqrt(max(0, 1 - (t / 24) ** 2))) / i0(8))
        scale = sum(row)
        phases.append([x / scale for x in row])
    return phases


if __name__ == "__main__":
    rows = coefficients()
    text = "#pragma once\n// Generated by tools/generate_modulation_fir.py; original ZYG windowed-sinc design.\n#include <array>\n\nnamespace zyg {\ninline constexpr int modulationFirTaps = 48;\ninline constexpr int modulationDelaySamples = 24;\ninline constexpr std::array<std::array<double, modulationFirTaps>, 4> modulationFir {{\n"
    for row in rows:
        text += "    {{\n" + "".join("        " + ", ".join(format(x, ".17g") for x in row[i:i+4]) + ",\n" for i in range(0, 48, 4)) + "    }},\n"
    text += "}};\n}\n"
    path = Path(__file__).resolve().parent.parent / "src/ModulationFir.h"
    path.write_text(text, encoding="utf-8", newline="\n")
    print(path)
